def outcome(est, hw, measured, scale=1.0):
    est = est * scale
    lo = est - hw * max(abs(est), 1.0) * (0.8 + 0.4 * RNG.random())
    hi = est + hw * max(abs(est), 1.0) * (0.8 + 0.4 * RNG.random())
    return {"est": r(est), "lo": r(lo), "hi": r(hi), "measured": measured}


