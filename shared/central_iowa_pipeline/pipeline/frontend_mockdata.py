def best_badge(eff, tid):
    """Best strategy (incl. S0) under the app's default utility: equal weights on goodness-signed outcomes
    (yield, soil loss, drought loss, nitrate), each scaled by its SD across all type x strategy estimates.
    Mirrors web/js/model.js so the map colours agree with the cards."""
    keys, sign = ["yield_pct", "erosion_t_ac", "drought_loss_pct", "nitrate_pct"], [1, -1, -1, -1]
    allv = {k: [s["outcomes"][k]["est"] for t in eff["by_type"].values() for s in t.values()] for k in keys}
    sd = {k: (float(np.std(v, ddof=1)) or 1.0) for k, v in allv.items()}
    util = {sid: sum(sg * s["outcomes"][k]["est"] / sd[k] for k, sg in zip(keys, sign)) for sid, s in eff["by_type"][tid].items()}
    best = max(sorted(util), key=lambda sid: util[sid])
    return best, eff["by_type"][tid][best]["badge"]


