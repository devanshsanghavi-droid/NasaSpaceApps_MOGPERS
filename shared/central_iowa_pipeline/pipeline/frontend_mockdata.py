def fields_index(eff):
    g = REGION["grid"]
    tr = Transformer.from_crs("EPSG:32615", "EPSG:4326", always_xy=True)
    rows_i, cols_i = np.meshgrid(np.arange(g["nrows"]), np.arange(g["ncols"]), indexing="ij")
    x = g["x0"] + cols_i * g["spacing_m"]
    y = g["y0"] - rows_i * g["spacing_m"]
    lon, lat = tr.transform(x.ravel(), y.ravel())
    lon, lat = np.asarray(lon), np.asarray(lat)
    gid = (rows_i * g["ncols"] + cols_i).ravel()

    # smooth synthetic "landscape" fields
    def smooth(a, b, c, d, ph):
        return np.sin(lon * a + ph) * np.cos(lat * b + ph * 0.7) + 0.5 * np.sin(lon * c + lat * d + ph * 1.3)

    s1, s2, s3 = smooth(9, 11, 23, 17, 0.3), smooth(14, 8, 31, 29, 1.7), smooth(21, 19, 41, 37, 2.9)
    p_field = 0.55 + 0.15 * s1
    # carve out Des Moines metro and Ames
    urban = (np.hypot((lon + 93.62) * 0.75, lat - 41.60) < 0.11) | (np.hypot((lon + 93.62) * 0.75, lat - 42.03) < 0.035)
    is_field = (RNG.random(lon.size) < p_field) & ~urban
    # When the CDL module's data/fields.parquet exists, reuse its REAL is_field mask, county names and
    # crop sequences so mock field ids (and hero ids) are valid is_field ids in the real export too.
    # Types, badges and every effect number stay synthetic.
    real = None
    fp = ROOT / "data" / "fields.parquet"
    if fp.exists():
        import pandas as pd
        real = pd.read_parquet(fp, columns=["field_id", "grid_id", "is_field", "county_name", "crop_seq_2016_2024"]).set_index("grid_id")
        if len(real) == lon.size and (real.index.values == gid).all():
            is_field = real["is_field"].to_numpy(bool)
        else:
            print("fields.parquet grid does not match region.json grid; using synthetic mask")
            real = None

    t = np.full(lon.size, "T1", dtype=object)
    t[s1 > 0.35] = "T2"
    t[(s2 > 0.7)] = "T3"
    t[(s3 > 0.9) | ((s1 < -0.9) & (s2 > 0.0))] = "T4"
    t[(s2 < -0.85)] = "T5"
    t[(s3 < -1.05)] = "T6"

    seq_cs = ["CSCSCSCSC", "SCSCSCSCS", "CSCSCCSCS", "SCSCSCSCC"]
    seq_cc = ["CCCCCCCCC", "CCCSCCCCC", "CCCCCSCCC"]
    seq_mx = ["CSCSOSCSC", "CSACSCSCS", "SCSCSSCSC"]
    best = {tid: best_badge(eff, tid) for tid in TYPE_IDS}

    rows = []
    for i in np.flatnonzero(is_field):
        name, _fips = county_of(lon[i], lat[i])
        tid = t[i]
        seq = (seq_cc if tid == "T5" else seq_mx if tid == "T6" else seq_cs)[int(RNG.integers(0, 3))]
        if real is not None:
            rr = real.loc[gid[i]]
            name = rr["county_name"] if isinstance(rr["county_name"], str) else name
            seq = rr["crop_seq_2016_2024"] if isinstance(rr["crop_seq_2016_2024"], str) and rr["crop_seq_2016_2024"] else seq
        rows.append([f"f{gid[i]:05d}", r(lon[i], 5), r(lat[i], 5), tid, seq, best[tid][1], name])
    return {"mock": True, "note": MOCK_NOTE + " badge_best = evidence badge of the top-ranked non-S0 strategy for the field's type.",
            "columns": ["field_id", "lon", "lat", "type_id", "seq", "badge_best", "county"], "rows": rows}


