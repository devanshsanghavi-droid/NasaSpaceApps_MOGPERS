def dump(name: str, obj) -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    path = OUT / name
    with open(path, "w") as f:
        json.dump(obj, f, separators=(",", ":"))
    print(f"wrote {path.relative_to(ROOT)}  ({path.stat().st_size/1024:.0f} KB)")


